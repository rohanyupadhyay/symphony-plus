defmodule SymphonyPlus.Documentation do
  @moduledoc "Deterministic reference facts from schema, CLI, and pinned build metadata."
  alias SymphonyPlus.Config.Schema

  @operator_docs ~w(README.md .symphony-plus/README.md elixir/README.md elixir/docs/agent-installation.md elixir/examples/github-speckit-README.md)
  @example_workflows ~w(.symphony-plus/WORKFLOW.md elixir/examples/github-speckit-WORKFLOW.md)

  @spec render(Path.t(), keyword()) :: {:ok, String.t()} | {:error, atom()}
  def render(root, project_config \\ Mix.Project.config()) do
    with {:ok, versions} <- pinned_versions(root),
         {:ok, project_version, release_targets} <- release_metadata(project_config) do
      {:ok, render_reference(versions, project_version, release_targets)}
    end
  end

  defp render_reference(versions, project_version, release_targets) do
    config_rows =
      for embed <- Schema.__schema__(:embeds),
          module = Schema.__schema__(:embed, embed).related,
          field <- module.__schema__(:fields),
          field != :id do
        default = module |> struct() |> Map.fetch!(field)
        "| `#{embed}.#{field}` | `#{inspect(module.__schema__(:type, field))}` | `#{escape(default)}` |"
      end

    cli_rows =
      for {command, options} <- Enum.sort(SymphonyPlus.CLI.options()), {name, type} <- options do
        "| #{command} | `--#{name |> Atom.to_string() |> String.replace("_", "-")}` | `#{type}` |"
      end

    Enum.join(
      [
        "# Configuration and CLI reference",
        "",
        "Generated by `mix docs.generate`; verify with `mix docs.check`. Do not edit by hand.",
        "",
        "These are raw schema defaults, before provider validation, environment resolution, or runtime path expansion.",
        "`nil` means unset; required provider settings still need explicit configuration. CLI options have no implicit values here.",
        "See [the implementation guide](../README.md#configuration) for precedence, secrets, and operational semantics.",
        "",
        "| Workflow key | Ecto type | Raw default |",
        "| --- | --- | --- |"
      ] ++
        config_rows ++
        ["", "| CLI command | Option | Type |", "| --- | --- | --- |"] ++
        cli_rows ++
        [
          "",
          "## Pinned build and release metadata",
          "",
          "| Fact | Declared value |",
          "| --- | --- |",
          "| Erlang (mise) | `#{versions.erlang}` |",
          "| Elixir (mise) | `#{versions.elixir}` |",
          "| Project version | `#{project_version}` |",
          "| Burrito targets | #{Enum.map_join(release_targets, ", ", &"`#{&1}`")} |",
          ""
        ],
      "\n"
    )
  end

  @spec check(Path.t()) :: :ok | {:error, [map()]}
  def check(root) do
    path = Path.join(root, "elixir/docs/configuration-reference.md")

    generated = generated_findings(root, path)

    findings =
      generated ++
        Enum.flat_map(@operator_docs, &check_links(root, &1)) ++
        Enum.flat_map(@example_workflows, &check_example(root, &1))

    case findings do
      [] -> :ok
      _ -> {:error, findings}
    end
  end

  defp escape(value), do: value |> inspect(limit: :infinity, printable_limit: :infinity) |> String.replace("|", "\\|")

  defp pinned_versions(root) do
    path = Path.join(root, "elixir/mise.toml")

    with {:ok, contents} <- File.read(path),
         entries = Regex.scan(~r/^\s*(erlang|elixir)\s*=\s*"([^"]+)"\s*$/m, contents, capture: :all_but_first),
         %{"erlang" => erlang, "elixir" => elixir} <- Map.new(entries, fn [name, version] -> {name, version} end) do
      {:ok, %{erlang: erlang, elixir: elixir}}
    else
      _ -> {:error, :invalid_pinned_tool_versions}
    end
  end

  defp release_metadata(project_config) do
    with {:ok, version} when is_binary(version) <- Keyword.fetch(project_config, :version),
         {:ok, releases} <- Keyword.fetch(project_config, :releases),
         {:ok, release} <- Keyword.fetch(releases, :symphony_plus),
         {:ok, burrito} <- Keyword.fetch(release, :burrito),
         {:ok, targets} when is_list(targets) and targets != [] <- Keyword.fetch(burrito, :targets) do
      {:ok, version, targets |> Keyword.keys() |> Enum.map(&Atom.to_string/1) |> Enum.sort()}
    else
      _ -> {:error, :invalid_release_metadata}
    end
  end

  defp generated_findings(root, path) do
    case render(root) do
      {:ok, rendered} ->
        if File.read(path) == {:ok, rendered},
          do: [],
          else: [%{code: :stale_generated_reference, path: path, message: "Run mix docs.generate from elixir/"}]

      {:error, reason} ->
        [%{code: reason, path: path, message: "Required pinned build or release metadata is unavailable"}]
    end
  end

  defp check_links(root, relative) do
    path = Path.join(root, relative)

    case File.read(path) do
      {:ok, contents} ->
        for [_, href] <- Regex.scan(~r/\[[^\]]+\]\(([^)]+)\)/, contents),
            local_reference?(href),
            target = href |> String.split("#", parts: 2) |> hd() |> URI.decode(),
            resolved = Path.expand(target, Path.dirname(path)),
            not File.exists?(resolved) do
          %{code: :missing_local_reference, path: path, message: "Missing local reference #{href}"}
        end

      {:error, _} ->
        [%{code: :missing_operator_document, path: path, message: "Maintained operator document is missing"}]
    end
  end

  defp local_reference?(href) do
    href != "" and not String.starts_with?(href, "#") and
      not Regex.match?(~r/^[a-z][a-z0-9+.-]*:/i, href)
  end

  defp check_example(root, relative) do
    path = Path.join(root, relative)

    with {:ok, contents} <- File.read(path),
         [_, yaml] <- Regex.run(~r/\A---\r?\n(.*?)\r?\n---/s, contents),
         {:ok, %{"tracker" => %{"kind" => "github", "provider" => provider}}} <- YamlElixir.read_from_string(yaml),
         true <- is_map(provider) and is_binary(provider["repo"]),
         %{"kind" => "github_app"} <- provider["auth"],
         true <- provider["bootstrap_clone"] == true do
      []
    else
      _ -> [%{code: :invalid_documented_workflow, path: path, message: "Expected GitHub App example with bootstrap_clone: true"}]
    end
  end
end
